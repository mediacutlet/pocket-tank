#!/usr/bin/env python3
"""gen_icons.py - bake assets/icons/*.png into common/icons.c + icons.h.

Full-color pixel-art icons, hand-drawn (the style: 16/24 px, hard edges,
three-tone shading). Each PNG becomes an icon_t: a palette
of its (RGB565, alpha) pairs + packed indices (0.4.2), or RGB565 pixels + an
8-bit alpha plane when it has more than 256 pairs; read with icon_at() and
blended at draw time by render.c's blit_icon().

Run from anywhere; paths are repo-relative to this file:
    ~/.venvs/pocket-tank/bin/python tools/gen_icons.py
"""
import os, re, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "icons")
OUT_C = os.path.join(ROOT, "common", "icons.c")
OUT_H = os.path.join(ROOT, "common", "icons.h")


def cname(fn):
    stem = os.path.splitext(fn)[0]
    return "icon_" + re.sub(r"[^a-z0-9]+", "_", stem.replace("icon_", "").lower()).strip("_")


def main():
    files = sorted(f for f in os.listdir(SRC) if f.endswith(".png"))
    if not files:
        sys.exit(f"no PNGs in {SRC}")
    decls, defs, table = [], [], []
    total = 0
    packed = 0
    hsh = 0x811c9dc5   # FNV-1a over every icon's pixels as drawn (rgb low, rgb high, alpha): sim --selftest-icons checks icon_at against it
    for fn in files:
        img = Image.open(os.path.join(SRC, fn)).convert("RGBA")
        w, h = img.size
        if w > 64 or h > 64:
            sys.exit(f"{fn}: {w}x{h} is too big for a UI icon (max 64)")
        px = list(img.getdata())
        rgb, alp = [], []
        for r, g, b, a in px:
            rgb.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) if a else 0)   # (a clear pixel's colour is never drawn: one pair for all of them)
            alp.append(a)
        n = cname(fn)
        total += w * h * 3
        for v, a in zip(rgb, alp):
            for byte in (v & 255, v >> 8, a):
                hsh = ((hsh ^ byte) * 0x01000193) & 0xffffffff
        # PACKED (0.4.2, the app's room): a palette of the icon's (colour, alpha) pairs and each pixel's index in
        # 1, 2, 4 or 8 bits, LSB first - the same pixels exactly. An icon with more than 256 pairs (soft edges) stays raw.
        pairs = sorted(set(zip(rgb, alp)))
        if len(pairs) <= 256:
            bits = 1 if len(pairs) <= 2 else 2 if len(pairs) <= 4 else 4 if len(pairs) <= 16 else 8
            at = {p: i for i, p in enumerate(pairs)}
            idx = bytearray((w * h * bits + 7) // 8)
            for k, p in enumerate(zip(rgb, alp)):
                bit = k * bits
                idx[bit >> 3] |= at[p] << (bit & 7)
            defs.append(f"static const uint16_t {n}_pal[{len(pairs)}] = {{\n"
                        + wrap(", ".join(f"0x{v:04x}" for v, _ in pairs)) + "\n};")
            defs.append(f"static const uint8_t {n}_pa[{len(pairs)}] = {{\n"
                        + wrap(", ".join(str(a) for _, a in pairs)) + "\n};")
            defs.append(f"static const uint8_t {n}_px[{len(idx)}] = {{\n"
                        + wrap(", ".join(str(v) for v in idx)) + "\n};")
            table.append(f"const icon_t {n} = {{ {w}, {h}, {bits}, {n}_pal, {n}_pa, {n}_px }};")
            packed += len(pairs) * 3 + len(idx)
        else:
            defs.append(f"static const uint16_t {n}_rgb[{w * h}] = {{\n"
                        + wrap(", ".join(f"0x{v:04x}" for v in rgb)) + "\n};")
            defs.append(f"static const uint8_t {n}_a[{w * h}] = {{\n"
                        + wrap(", ".join(str(v) for v in alp)) + "\n};")
            table.append(f"const icon_t {n} = {{ {w}, {h}, 0, {n}_rgb, {n}_a, 0 }};")
            packed += w * h * 3
        decls.append(f"extern const icon_t {n};")
    hdr = (
        "/* icons.h - GENERATED by tools/gen_icons.py from the assets/icons PNGs.\n"
        " * Do not edit by hand; re-run the script after changing the art. */\n"
        "#ifndef POCKET_TANK_ICONS_H\n#define POCKET_TANK_ICONS_H\n"
        "#include <stdint.h>\n\n"
        "/* bits 1/2/4/8: px holds each pixel's index into pal (RGB565) / pa (alpha), packed LSB first;\n"
        " * bits 0: a raw icon, pal = w*h RGB565 pixels, pa = w*h alphas (more than 256 pairs). */\n"
        "typedef struct { uint8_t w, h, bits; const uint16_t *pal; const uint8_t *pa; const uint8_t *px; } icon_t;\n"
        "static inline void icon_at(const icon_t *ic, int k, uint16_t *rgb, uint8_t *a) {   /* pixel k (row-major) */\n"
        "    unsigned v = (unsigned)k;\n"
        "    if (ic->bits) { unsigned b = ic->bits, bit = (unsigned)k * b; v = (ic->px[bit >> 3] >> (bit & 7)) & ((1u << b) - 1); }\n"
        "    *rgb = ic->pal[v]; *a = ic->pa[v];\n"
        "}\n\n"
        + "\n".join(decls) + "\n\n"
        + f"#define ICONS_N {len(files)}\n#define ICONS_PIXEL_HASH 0x{hsh:08x}u\n"
        + "extern const icon_t *const icons_all[ICONS_N];   /* every icon, for the sim's check (the firmware's linker drops it) */\n\n#endif\n")
    src = (
        "/* icons.c - GENERATED by tools/gen_icons.py from the assets/icons PNGs. */\n"
        '#include "icons.h"\n\n' + "\n\n".join(defs) + "\n\n" + "\n".join(table) + "\n\n"
        + "const icon_t *const icons_all[ICONS_N] = {\n" + wrap(", ".join("&" + cname(f) for f in files)) + "\n};\n")
    open(OUT_H, "w").write(hdr)
    open(OUT_C, "w").write(src)
    print(f"wrote {len(files)} icons, {total / 1024:.1f} KB raw -> {packed / 1024:.1f} KB packed")
    for f in files:
        print(f"  {cname(f)}")


def wrap(s, width=100):
    out, line = [], "    "
    for tok in s.split(", "):
        if len(line) + len(tok) + 2 > width:
            out.append(line.rstrip())
            line = "    "
        line += tok + ", "
    out.append(line.rstrip().rstrip(","))
    return "\n".join(out)


if __name__ == "__main__":
    main()
