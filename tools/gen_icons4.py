#!/usr/bin/env python3
"""gen_icons4.py - bake assets/icons4/*.png into common/icons4.c + icons4.h.

Small flat icons (the fish card's buttons, 0.4.2) as 4-bit palette indices:
index 0 is clear, up to 15 opaque colors, two pixels a byte (high nibble
first). A 36 x 36 icon is 648 bytes + its palette, against 3888 as an
icon_t. No PIL: the PNG reader below takes 8-bit RGB/RGBA, non-interlaced.
Alpha must be 0 or 255 (the art is hard-edged pixel work).

    python3 tools/gen_icons4.py
"""
import os, struct, sys, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "icons4")


def read_png(path):
    data = open(path, "rb").read()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", path
    pos, idat, w = 8, b"", 0
    while pos < len(data):
        n, typ = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        if typ == b"IHDR":
            w, h, depth, ctype, _, _, inter = struct.unpack(">IIBBBBB", body)
            assert depth == 8 and ctype in (2, 6) and inter == 0, (path, depth, ctype, inter)
            bpp = 4 if ctype == 6 else 3
        elif typ == b"IDAT":
            idat += body
        pos += 12 + n
    raw, stride, rows, prev = zlib.decompress(idat), w * bpp, [], bytearray(w * bpp)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b, c = prev[i], prev[i - bpp] if i >= bpp else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append([tuple(line[x * bpp:x * bpp + 3]) + ((line[x * bpp + 3],) if bpp == 4 else (255,)) for x in range(w)])
        prev = line
    return w, h, rows


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def wrap(items, per=16):
    return ",\n".join("    " + ", ".join(items[i:i + per]) for i in range(0, len(items), per))


def main():
    names = sorted(f for f in os.listdir(SRC) if f.endswith(".png"))
    h_out = ["/* icons4.h - GENERATED by tools/gen_icons4.py from the assets/icons4 PNGs. */",
             "#ifndef POCKET_TANK_ICONS4_H", "#define POCKET_TANK_ICONS4_H", "#include <stdint.h>", "",
             "/* 4-bit palette icons: px holds two indices a byte (high nibble first), 0 = clear */",
             "typedef struct { uint8_t w, h, n; const uint16_t *pal; const uint8_t *px; } icon4_t;", ""]
    c_out = ["/* icons4.c - GENERATED by tools/gen_icons4.py from the assets/icons4 PNGs. */",
             '#include "icons4.h"', ""]
    total = 0
    for fn in names:
        name = "icon4_" + os.path.splitext(fn)[0].replace("-", "_")
        w, h, rows = read_png(os.path.join(SRC, fn))
        pal, idx = [], []
        for y in range(h):
            for x in range(w):
                p = rows[y][x]
                if p[3] == 0: idx.append(0); continue
                assert p[3] == 255, "%s: soft alpha at %d,%d" % (fn, x, y)
                k = rgb565(*p[:3])
                if k not in pal: pal.append(k)
                idx.append(pal.index(k) + 1)
        assert len(pal) <= 15, "%s: %d colors (15 at most)" % (fn, len(pal))
        if len(idx) % 2: idx.append(0)
        packed = ["0x%02x" % (idx[i] << 4 | idx[i + 1]) for i in range(0, len(idx), 2)]
        c_out += ["static const uint16_t %s_pal[%d] = {\n%s\n};" % (name, len(pal), wrap(["0x%04x" % v for v in pal], 8)),
                  "static const uint8_t %s_px[%d] = {\n%s\n};" % (name, len(packed), wrap(packed, 18)),
                  "const icon4_t %s = { %d, %d, %d, %s_pal, %s_px };" % (name, w, h, len(pal), name, name), ""]
        h_out.append("extern const icon4_t %s;" % name)
        total += len(packed) + 2 * len(pal) + 8
    h_out += ["", "#endif", ""]
    open(os.path.join(ROOT, "common", "icons4.h"), "w").write("\n".join(h_out))
    open(os.path.join(ROOT, "common", "icons4.c"), "w").write("\n".join(c_out))
    print("icons4: %d icons, %d bytes" % (len(names), total))


if __name__ == "__main__":
    sys.exit(main())
